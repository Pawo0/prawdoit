def run_scenario(sc: dict, eng: Engine, pages: Pages, corpus: Corpus) -> dict:
    t0 = time.perf_counter()
    checks, got, raws, unsupported = deps_checks(sc, corpus), "", [], None
    try:
        c, got, raws, unsupported = DRIVERS[sc["drive"]["kind"]](sc, eng, pages, corpus)
        checks += c
    except Exception as e:  # noqa: BLE001 — a crash is a failed scenario with its traceback, never a skipped one
        checks.append(Check("the scenario ran without an exception", False, f"{type(e).__name__}: {e}"))
        got, raws = f"exception: {type(e).__name__}: {e}", [{"label": "traceback", "traceback": traceback.format_exc()}]
    failed = [c for c in checks if c.gating and not c.ok]
    outcome = "UNSUPPORTED" if unsupported else ("FAIL" if failed else "PASS")
    pubs = publications(sc, corpus)
    cause = "" if outcome == "PASS" else ("input kind not implemented" if unsupported else
                                          "publication missing from the corpus" if any(not p["in_corpus"] for p in pubs) else
                                          "fails although the publication is in the corpus" if pubs else "no publication involved")
    reason = unsupported or "; ".join(c.name for c in failed[:4]) + (f"; … +{len(failed) - 4} more" if len(failed) > 4 else "")
    return scrub({"id": sc["id"], "scenario": sc["scenario"], "variant": sc["variant"], "derived": sc.get("derived", False),
            "tier": sc["tier"], "drive": sc["drive"]["kind"], "question": sc["question"], "expected": sc["expected_summary"],
            "got": got, "outcome": outcome, "reason": reason, "failure_class": cause, "publications": pubs,
            "checks": [asdict(c) for c in checks], "advisory_missed": [c.name for c in checks if not c.gating and not c.ok],
            "runs": raws, "seconds": round(time.perf_counter() - t0, 2)})


