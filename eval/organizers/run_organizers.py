class Corpus:
    """Corpus records read straight from data/corpus/*.jsonl — independent of the index, for the verbatim-quote check."""

    def __init__(self, corpus_dir: Path):
        self.dir, self._docs = corpus_dir, None
        self.live: list[dict] = []  # records received from a live provider during a network-tier scenario

    def docs(self) -> dict[str, dict]:
        if self._docs is None:
            self._docs = {}
            for f in sorted(self.dir.glob("*.jsonl")):
                for line in f.read_text(encoding="utf-8").splitlines():
                    if not line.strip():
                        continue
                    try:
                        d = json.loads(line)
                    except ValueError:
                        continue
                    self._docs.setdefault(d.get("id"), {**d, "_file": f.name})
        return self._docs

    def get(self, doc_id: str) -> dict | None:
        return self.docs().get(doc_id)

    def by_url(self, url: str) -> list[dict]:
        return [d for d in self.docs().values() if same_url(d.get("url"), url)]


class Pages:
    """Loopback server for the controlled pages (only the files the scenarios name; everything else is 404)."""

    def __init__(self, files: list[str]):
        table = {f"/{p}": (ROOT / p).read_bytes() for p in files}

        class Handler(http.server.BaseHTTPRequestHandler):
            def do_GET(self):  # noqa: N802
                body = table.get(self.path.split("?")[0])
                self.send_response(200 if body is not None else 404)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Length", str(len(body or b"")))
                self.end_headers()
                self.wfile.write(body or b"")

            def log_message(self, *args):
                pass

        self.srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.base = f"http://127.0.0.1:{self.srv.server_address[1]}"
        threading.Thread(target=self.srv.serve_forever, daemon=True).start()

    def url(self, page: str) -> str:
        return f"{self.base}/{page}"

    @contextlib.contextmanager
    def reachable(self, eng: Engine):
        """The SSRF guard rejects loopback addresses (as it must). Lift it for THIS server only, so the real fetch
        path (httpx, size/time limits, trafilatura, injection scan) runs on the controlled page."""
        real = eng.security.check_public_url
        with mock.patch.object(eng.fetch, "check_public_url",
                               lambda u: u.strip() if u.strip().startswith(self.base + "/") else real(u)):
            yield

    def close(self) -> None:
        self.srv.shutdown()


@contextlib.contextmanager
def environ(**kv: str):
    old = {k: os.environ.get(k) for k in kv}
    os.environ.update(kv)
    try:
        yield
    finally:
        for k, v in old.items():
            os.environ.pop(k, None) if v is None else os.environ.__setitem__(k, v)


@contextlib.contextmanager
def hidden_publication(eng: Engine, url: str):
    """Make one publication unfindable in the local index for the duration of a scenario — simulates 'the live
    index is the only place where this article can be found'. Its embedding rows are zeroed (neither claim matching
    nor passage retrieval can return it) and its id / URL are renamed, so a copy arriving from a live provider is
    accepted as a new document. Yields the number of documents hidden (0 = it was not in the corpus anyway)."""
    ix, want = eng.INDEX, url.rstrip("/")
    docs = {i for i, d in enumerate(ix.docs) if d.url.rstrip("/") == want}
    chunks = [c for i in docs for c in ix.doc_chunks[i]]
    claims = [r for r, di in enumerate(ix.claim_doc_idx) if di in docs]
    saved = ix.chunk_emb[chunks].copy(), ix.claim_emb[claims].copy()
    names = {i: (ix.docs[i].id, ix.docs[i].url) for i in docs}
    ix.chunk_emb[chunks], ix.claim_emb[claims] = 0.0, 0.0
    for i in docs:
        ix.docs[i].id, ix.docs[i].url = names[i][0] + HIDDEN, names[i][1].rstrip("/") + "/" + HIDDEN
    try:
        yield len(docs)
    finally:
        ix.chunk_emb[chunks], ix.claim_emb[claims] = saved
        for i, (doc_id, doc_url) in names.items():
            ix.docs[i].id, ix.docs[i].url = doc_id, doc_url


HIDDEN = "#hidden-by-organizers-test"


# ====================================================================================================== text helpers
def norm(s: str | None) -> str:
    return re.sub(r"\s+", " ", unicodedata.normalize("NFC", s or "")).strip()


def same_url(a: str | None, b: str | None) -> bool:
    return bool(a and b) and a.rstrip("/").lower() == b.rstrip("/").lower()


def find_any(patterns: list[str], text: str):
    for p in patterns:
        m = re.search(p, text, FLAGS)
        if m:
            return m
    return None


def group_hit(group: dict, text: str) -> str | None:
    """The text that satisfies an expectation group, or None. With `unless`, matching is per sentence."""
    if not group.get("unless"):
        m = find_any(group["any"], text)
        return text[max(0, m.start() - 40): m.end() + 40] if m else None
    for sent in re.split(r"(?<=[.!?…])\s+", text):
        if find_any(group["any"], sent) and not find_any(group["unless"], sent):
            return sent[:200]
    return None


@dataclass
class Check:
    name: str
    ok: bool
    detail: str = ""
    gating: bool = True


@dataclass
class Obs:
    """One answer of the system as the user sees it."""
    question: str
    res: object  # CheckResult
    reply_raw: str  # chat message (second-channel rendering of the same result)
    reply: str
    page: str

    @property
    def claim(self):
        return self.res.claims[0] if self.res.claims else None

    def main(self, claim=None):
        c = claim or self.claim
        if c is None or c.main_evidence is None or c.main_evidence >= len(c.evidence):
            return None
        return c.evidence[c.main_evidence]


def page_text(res, reply: str) -> str:
    parts = [reply, res.short_answer, res.status_message, res.case_status, *res.warnings]
    if res.live_search:
        parts.append(res.live_search.notice)
    for c in res.claims:
        parts += [c.short_answer, c.basis_line, c.limitation_line, c.explanation, c.missing_context, c.what_unknown,
                  c.would_settle, *c.limitations]
        for e in c.evidence:
            parts += [e.publisher, e.title, e.url, e.published_at, e.fragment, e.factcheck_claim, e.factcheck_verdict_raw]
    return norm(" \n ".join(p for p in parts if p))


def observe(eng: Engine, question: str, res, reply: str | None = None) -> Obs:
    reply = eng.chat_text(res) if reply is None else reply
    return Obs(question, res, reply, norm(reply), page_text(res, reply))


def dump(o: Obs, label: str = "") -> dict:
    res, m = o.res, o.main()
    return {"label": label, "question": o.question, "check_id": res.id, "channel": res.channel, "status": res.status,
            "status_message": res.status_message, "verdicts": [c.verdict for c in res.claims],
            "rules": [c.rules_fired for c in res.claims], "reason_codes": [c.reason_codes for c in res.claims],
            "short_answer": res.short_answer, "reply": o.reply_raw,
            "main_evidence": {"doc_id": m.doc_id, "url": m.url, "fragment": m.fragment} if m else None,
            "evidence": [{"doc_id": e.doc_id, "url": e.url, "stance": e.stance, "similarity": e.similarity,
                          "same_claim": e.same_claim, "fragment": e.fragment[:300]} for e in (o.claim.evidence if o.claim else [])],
            "warnings": res.warnings, "security_events": [asdict_event(e) for e in res.security_events],
            "case_id": res.case_id, "case_status": res.case_status,
            "live_search": res.live_search.model_dump() if res.live_search else None,
            "url_meta": res.url_meta, "total_ms": res.timings_ms.get("total_ms")}


def asdict_event(e) -> dict:
    return {"kind": e.kind, "where": e.where, "detail": e.detail[:160]}


def got_line(o: Obs) -> str:
    res, m = o.res, o.main()
    head = "/".join(c.verdict for c in res.claims) or res.status
    src = f" [{m.publisher}: {m.url}]" if m else ""
    return f"{head}: {norm(res.short_answer or res.status_message)[:170]}{src}"


# ====================================================================================================== checks
def invariants(o: Obs, eng: Engine, corpus: Corpus, pre: str = "") -> list[Check]:
    """Properties every answer must have, whatever the scenario (task statement: no fabricated sources, a failure
    is never a verdict, a case is announced only when it was really recorded)."""
    res, out = o.res, []
    bad = []
    for c in res.claims:
        if c.verdict not in DECISIVE:
            continue
        m = o.main(c)
        if m is None:
            bad.append(f"{c.verdict} without a decisive source")
        else:
            why = quote_problem(m, corpus)
            if why:
                bad.append(why)
    out.append(Check(pre + "every verdict rests on a source quoted verbatim from the corpus", not bad, "; ".join(bad)))
    if res.status != "ok":
        out.append(Check(pre + "a non-verdict status carries no verdict", not res.claims,
                         f"status {res.status} with verdicts {[c.verdict for c in res.claims]}"))
    ids = set(re.findall(r"SPR-[0-9A-F]{6}", o.reply_raw + " " + (res.case_status or "")))
    if res.case_id:
        ids.add(res.case_id)
    missing = [i for i in ids if not case_has(eng, i, res.id)]
    out.append(Check(pre + "a case is mentioned only if the store really recorded this submission", not missing,
                     f"announced but not recorded: {missing}" if missing else ""))
    ms = res.timings_ms.get("total_ms") or 0
    out.append(Check(pre + f"answered within {MAX_ANSWER_MS // 1000} s", ms <= MAX_ANSWER_MS, f"{ms:.0f} ms"))
    return out


def case_row(eng: Engine, case_id: str) -> dict | None:
    r = eng.store._db.execute("SELECT id, count, channels, sample_check_ids, status FROM cases WHERE id=?", (case_id,)).fetchone()
    return {**dict(r), "channels": json.loads(r["channels"]), "sample_check_ids": json.loads(r["sample_check_ids"])} if r else None


def case_has(eng: Engine, case_id: str, check_id: str) -> bool:
    row = case_row(eng, case_id)
    return bool(row) and check_id in row["sample_check_ids"]


def quote_problem(e, corpus: Corpus) -> str:
    """'' when the quoted fragment is a verbatim part of the stored source record (checked against the JSONL file,
    not through the engine)."""
    cands = [d for d in [corpus.get(e.doc_id), *(x for x in corpus.live if x.get("id") == e.doc_id)] if d]
    if not cands:
        return f"quoted document {e.doc_id} is not in data/corpus"
    if not norm(e.fragment):
        return f"empty quote from {e.doc_id}"
    why = ""
    for d in cands:  # the corpus file first; in the network tier also the record received from the live provider
        if norm(e.fragment) not in norm(f"{d.get('title') or ''}. {d.get('text') or ''}") and norm(e.fragment) not in norm(d.get("text")):
            why = why or f"quote is not verbatim in {e.doc_id}: “{e.fragment[:80]}…”"
        elif not same_url(d.get("url"), e.url):
            why = why or f"link {e.url} differs from the record of {e.doc_id}"
        else:
            return ""
    return why


def evaluate(exp: dict, o: Obs, eng: Engine, corpus: Corpus, ctx: dict | None = None, gating: bool = True,
             pre: str = "") -> list[Check]:
    ctx, res, out = ctx or {}, o.res, []
    add = lambda name, ok, detail="": out.append(Check(pre + name, bool(ok), detail if not ok else "", gating))  # noqa: E731
    verdicts = [c.verdict for c in res.claims]
    main = o.main()
    all_ev = [e for c in res.claims for e in c.evidence]

    if "status_in" in exp:
        add(f"status is {' or '.join(exp['status_in'])}", res.status in exp["status_in"], f"status {res.status}: {res.status_message or ''}")
    if "verdict_in" in exp:
        ok = all(v in exp["verdict_in"] for v in verdicts) if verdicts else res.status != "ok"
        add(f"verdict is {' or '.join(exp['verdict_in'])}", ok, f"got {verdicts or 'no claim recognised'}")
    if "verdict_not_in" in exp:
        add(f"verdict is not {' / '.join(exp['verdict_not_in'])}", not any(v in exp["verdict_not_in"] for v in verdicts), f"got {verdicts}")
    if exp.get("single_claim"):
        add("the message is treated as one claim", len(verdicts) == 1, f"{len(verdicts)} claims: {[c.claim[:60] for c in res.claims]}")
    if exp.get("no_conflict"):
        conflict = any(c.conflicting or "ZRODLA_SPRZECZNE" in c.reason_codes for c in res.claims)
        add("not reported as 'conflicting sources'", not conflict, "result flagged as conflicting sources")
    if "opener" in exp:
        add(exp["opener"]["name"], find_any(exp["opener"]["any"], norm(res.short_answer)), f"answer: “{norm(res.short_answer)[:90]}”")
    if "opener_not" in exp:
        add(exp["opener_not"]["name"], not find_any(exp["opener_not"]["any"], norm(res.short_answer)), f"answer: “{norm(res.short_answer)[:90]}”")
    if "cites_main" in exp:
        add("decisive source is the expected publication", main is not None and same_url(main.url, exp["cites_main"]),
            f"expected {exp['cites_main']}, decisive source: {main.url if main else 'none'}")
    if "not_cites_main" in exp:
        add("the fact-check is NOT used as the decisive source", not (main and same_url(main.url, exp["not_cites_main"])), f"decisive source: {main.url if main else ''}")
    if exp.get("no_main_evidence"):
        add("no decisive source is presented", all(o.main(c) is None for c in res.claims), f"decisive source: {main.url if main else ''}")
    if "cites_evidence" in exp:
        add("the expected publication is among the shown sources", any(same_url(e.url, exp["cites_evidence"]) for e in all_ev),
            f"expected {exp['cites_evidence']}; shown: {[e.doc_id for e in all_ev][:6]}")
    if "cites_shown" in exp:
        add("the reply links the expected publication", exp["cites_shown"].rstrip("/").lower() in o.reply.lower(), f"no link to {exp['cites_shown']} in the reply")
    if "quote" in exp:
        q = exp["quote"]
        e = main if q["of"] == "main" else next((x for x in all_ev if same_url(x.url, q["of"])), None)
        if e is None:
            add("quote from the expected publication is shown", False,
                "there is no decisive source" if q["of"] == "main" else "the publication is not among the evidence")
        else:
            if q.get("verbatim"):
                why = quote_problem(e, corpus)
                add("the quote is verbatim in the corpus record", not why, why)
            if q.get("supports_any"):
                add("the quote itself carries the finding", find_any(q["supports_any"], norm(e.fragment)),
                    f"quote “{norm(e.fragment)[:140]}” matches none of {q['supports_any']}")
    if "quoted_factchecks_only" in exp:
        ans = norm(res.short_answer).lower()
        foreign = [e.doc_id for e in all_ev if e.factcheck_claim and norm(e.factcheck_claim)[:40].lower() in ans
                   and not any(same_url(e.url, u) for u in exp["quoted_factchecks_only"])]
        add("the answer quotes no other fact-check than the expected one", not foreign, f"answer quotes {foreign}")
    for key, surface, positive in (("reply_must", o.reply, True), ("page_must", o.page, True),
                                   ("reply_must_not", o.reply, False), ("page_must_not", o.page, False),
                                   ("ocr_must", norm(getattr(res, "input_excerpt", "")), True)):
        for g in exp.get(key, []):
            hit = group_hit(g, surface)
            where = {"reply_must": "reply", "page_must": "page", "reply_must_not": "reply", "page_must_not": "page", "ocr_must": "read text"}[key]
            if positive:
                add(f"{where}: {g['name']}", hit is not None, f"none of {g['any']} found")
            else:
                add(f"{where} never: {g['name']}", hit is None, f"found “{(hit or '')[:160]}”")
    if exp.get("page_fetched"):
        got = (res.url_meta or {}).get("url")
        add("the linked page was fetched", same_url(got, ctx.get("url")), f"url_meta: {res.url_meta}; warnings: {res.warnings[:2]}")
    if "security" in exp:
        s = exp["security"]
        ev = [e for e in res.security_events if e.kind == s["kind"] and find_any(s.get("where_any", [""]), e.where)]
        add(f"security event recorded in the result (≥ {s['min_events']} × {s['kind']} from the page)", len(ev) >= s["min_events"],
            f"events: {[(e.kind, e.where) for e in res.security_events]}")
        if s.get("stored"):
            n = eng.store._db.execute("SELECT COUNT(*) n FROM security_events WHERE check_id=? AND kind=?", (res.id, s["kind"])).fetchone()["n"]
            add("security event stored in the audit database", n >= s["min_events"], f"{n} rows for check {res.id}")
    if exp.get("same_as_control"):
        c = ctx.get("control")
        sig = lambda r: ([x.verdict for x in r.claims], [e.url for x in r.claims for e in x.evidence])  # noqa: E731
        main_c = observe(eng, "", c).main() if c is not None else None
        add("verdict unchanged by the page (same as without it)", c is not None and sig(c)[0] == sig(res)[0], f"{sig(c)[0] if c else None} vs {sig(res)[0]}")
        add("decisive source unchanged by the page", c is not None and main and main_c and same_url(main.url, main_c.url),
            f"{main_c.url if main_c else None} vs {main.url if main else None}")
        add("evidence list unchanged by the page", c is not None and sig(c)[1] == sig(res)[1], "evidence differs from the control run")
    if "live_status" in exp:
        ls = res.live_search
        add(f"live stage ran and reported status '{exp['live_status']}'", ls is not None and ls.status == exp["live_status"], f"live_search: {ls.model_dump() if ls else None}")
    if "google" in exp:
        g = exp["google"]
        step = next((x for x in (res.live_search.steps if res.live_search else []) if x.get("provider") == "google_factcheck"), None)
        add(f"Google Fact Check answered: status '{g['status']}', ≥ {g['min_results']} review(s) from registry domains",
            step is not None and step.get("status") == g["status"] and (step.get("n_results") or 0) >= g["min_results"],
            f"google step: {step}")
    if "error_logged" in exp:
        comps = [r["component"] for r in eng.store._db.execute("SELECT component FROM errors WHERE check_id=?", (res.id,)).fetchall()]
        add("the failure is logged (errors table)", any(find_any(exp["error_logged"], c) for c in comps), f"components logged: {comps}")
    return out


# ====================================================================================================== drivers
def deps_checks(sc: dict, corpus: Corpus) -> list[Check]:
    out = []
    for d in sc.get("depends_on", []):
        recs = corpus.by_url(d["url"])  # by URL: the same article may sit in another corpus file under another id
        out.append(Check(f"corpus contains {d['publisher']} “{d['title'][:60]}”", bool(recs),
                         ", ".join(f"{r['_file']}: {r['id']}" for r in recs) if recs
                         else f"no record with URL {d['url']} in data/corpus — the scenario cannot pass without it"))
    return out


def publications(sc: dict, corpus: Corpus) -> list[dict]:
    return [{"url": d["url"], "publisher": d["publisher"], "title": d["title"],
             "in_corpus": bool(corpus.by_url(d["url"])), "records": [f"{r['_file']}: {r['id']}" for r in corpus.by_url(d["url"])]}
            for d in sc.get("depends_on", [])]


def both(sc: dict, o: Obs, eng: Engine, corpus: Corpus, ctx: dict | None = None, pre: str = "") -> list[Check]:
    return (evaluate(sc["expect"], o, eng, corpus, ctx, True, pre) + evaluate(sc.get("advisory", {}), o, eng, corpus, ctx, False, pre)
            + invariants(o, eng, corpus, pre))


def drive_text(sc, eng, pages, corpus):
    checks, raws, first = [], [], None
    for i, q in enumerate([sc["question"], *sc.get("alt_questions", [])]):
        o = observe(eng, q, eng.check(q))
        first = first or o
        checks += both(sc, o, eng, corpus, pre="" if i == 0 else f"[other filling {i}] ")
        raws.append(dump(o, "main" if i == 0 else f"other filling {i}"))
    return checks, got_line(first), raws, None


def drive_url(sc, eng, pages, corpus):
    d = sc["drive"]
    url = pages.url(d["page"])
    q = sc["question"].replace("{url}", url)
    control = eng.check(d["control_question"]) if d.get("control_question") else None
    with pages.reachable(eng):
        o = observe(eng, q, eng.check(q))
    raws = [dump(o, "with the controlled page")] + ([dump(observe(eng, d["control_question"], control), "control: same question without the page")] if control else [])
    return both(sc, o, eng, corpus, {"url": url, "control": control}), got_line(o), raws, None


def drive_channels(sc, eng, pages, corpus):
    q, second = sc["question"], sc["drive"]["second"]
    web = observe(eng, q, eng.check(q, "web"))
    db = eng.store._db
    n0 = db.execute("SELECT COUNT(*) n FROM checks WHERE channel=?", (second,)).fetchone()["n"]
    if second == "whatsapp":  # the same payload shape Meta sends to the webhook; demo=True returns the reply instead of sending it
        payload = {"entry": [{"changes": [{"value": {"messages": [{"from": "48500100200", "type": "text", "text": {"body": q}}]}}]}]}
        replies = eng.meta._wa_process(payload, demo=True)
    else:
        payload = {"entry": [{"messaging": [{"sender": {"id": "organizers-test"}, "message": {"text": q}}]}]}
        replies = eng.meta._fb_process(payload, demo=True)
    rows = db.execute("SELECT id FROM checks WHERE channel=? ORDER BY rowid DESC LIMIT 1", (second,)).fetchone()
    n1 = db.execute("SELECT COUNT(*) n FROM checks WHERE channel=?", (second,)).fetchone()["n"]
    checks = [Check(f"the {second} adapter produced exactly one reply and one audited check", len(replies) == 1 and n1 == n0 + 1,
                    f"replies={len(replies)}, new checks={n1 - n0}")]
    if not replies or rows is None:
        return checks, got_line(web), [dump(web, "web")], None
    other = observe(eng, q, eng.CheckResult(**eng.store.get_check(rows["id"])), reply=replies[0]["body"])
    checks += both(sc, web, eng, corpus, pre="[web] ") + both(sc, other, eng, corpus, pre=f"[{second}] ")
    wm, om = web.main(), other.main()
    ev = lambda o: [e.url for c in o.res.claims for e in c.evidence]  # noqa: E731
    checks += [
        Check("channels: same verdict", [c.verdict for c in web.res.claims] == [c.verdict for c in other.res.claims],
              f"web {[c.verdict for c in web.res.claims]} vs {second} {[c.verdict for c in other.res.claims]}"),
        Check("channels: same decisive publication", bool(wm and om) and same_url(wm.url, om.url), f"web {wm.url if wm else None} vs {second} {om.url if om else None}"),
        Check("channels: same evidence list", ev(web) == ev(other), "evidence lists differ"),
        Check("channels: same short answer text", norm(web.res.short_answer) == norm(other.res.short_answer), "short answers differ"),
        Check(f"channels: the {second} message carries the short answer", norm(web.res.short_answer) in other.reply, "short answer missing from the message"),
    ]
    return checks, got_line(web) + f" | {second}: same result" * all(c.ok for c in checks[-5:]), [dump(web, "web"), dump(other, second)], None


def drive_pair(sc, eng, pages, corpus):
    d, exp = sc["drive"], sc["expect"]
    q1, q2 = sc["question"], d["paraphrase"]
    o1 = observe(eng, q1, eng.check(q1, "web"))
    o2 = observe(eng, q2, eng.check(q2, d.get("second_channel", "web")))
    checks = both(sc, o1, eng, corpus, pre="[first] ") + both(sc, o2, eng, corpus, pre="[paraphrase] ")
    c1, c2 = o1.res.case_id, o2.res.case_id
    row = case_row(eng, c1) if c1 else None
    want = exp["one_case"]["count"]
    checks += [
        Check("loop: the first submission created a case", bool(c1) and row is not None, f"case_id={c1}"),
        Check("loop: the paraphrase was assigned to the SAME case", bool(c1) and c1 == c2, f"{c1} vs {c2}"),
        Check(f"loop: the case counter is {want} and lists both submissions",
              bool(row) and row["count"] == want and row["sample_check_ids"] == [o1.res.id, o2.res.id], f"case row: {row}"),
        Check("loop: when the store confirmed the record, the reply says so", all(find_any(exp["case_notice"], o.reply) for o in (o1, o2)),
              "no case notice in the reply", gating=False),
    ]
    raws = [dump(o1, "first submission"), dump(o2, "paraphrase")]
    if d.get("store_failure_probe"):  # "Bot informuje o zapisie tylko wtedy, gdy system go potwierdził."
        with mock.patch.object(eng.store, "upsert_case", side_effect=RuntimeError("organizers test: simulated case-store failure")):
            o3 = observe(eng, q1, eng.check(q1, "web"))
        row3 = case_row(eng, c1) if c1 else None
        checks += [
            Check("loop/store down: the answer is still an abstention", o3.res.status == "ok" and [c.verdict for c in o3.res.claims] == ["brak_dowodow"],
                  f"{o3.res.status} {[c.verdict for c in o3.res.claims]}"),
            Check("loop/store down: the reply does NOT claim the submission was recorded",
                  not find_any(exp["case_notice"], o3.reply) and not o3.res.case_id and not o3.res.case_status,
                  f"reply: “{o3.reply[-220:]}” case_status={o3.res.case_status}"),
            Check("loop/store down: the case counter did not move", bool(row3) and row3["count"] == want, f"case row: {row3}"),
        ] + invariants(o3, eng, corpus, "[store down] ")
        raws.append(dump(o3, "case store failing"))
    return checks, got_line(o1) + f" | case {c1}: count {row['count'] if row else '-'}", raws, None


def drive_forced(sc, eng, pages, corpus):
    d, q = sc["drive"], sc["question"]
    checks = []
    with contextlib.ExitStack() as st:
        st.enter_context(environ(PRAWDOWID_LIVE_SEARCH="1", PRAWDOWID_FORCE_FAIL=d["force_fail"]))
        if d.get("hide_publication"):
            st.enter_context(hidden_publication(eng, d["hide_publication"]))
        o = observe(eng, q, eng.check(q))
    if d.get("hide_publication"):
        seen = any(HIDDEN in e.url or HIDDEN in e.doc_id or same_url(e.url, d["hide_publication"]) for c in o.res.claims for e in c.evidence)
        checks.append(Check("harness: the hidden publication did not reach the answer", not seen, "it is still among the evidence"))
    return checks + both(sc, o, eng, corpus), got_line(o), [dump(o, f"PRAWDOWID_FORCE_FAIL={d['force_fail']}")], None


def drive_live(sc, eng, pages, corpus):
    """Network tier: the real live stage (Google Fact Check Tools; trusted-site search as the application's own
    fallback). The key is put into the environment for this scenario only; requests use a neutral User-Agent."""
    d, q = sc["drive"], sc["question"]
    if not SECRETS:
        return [Check("Google Fact Check key is available", False, f"set {KEY_VAR} or pass --google-key-file <dotenv file>")], "no API key", [], None
    n0 = len(eng.INDEX.docs)
    with contextlib.ExitStack() as st:
        st.enter_context(environ(PRAWDOWID_LIVE_SEARCH="1", **{KEY_VAR: SECRETS[0]}))
        st.enter_context(mock.patch.object(eng.websearch, "UA", NEUTRAL_UA))
        st.enter_context(mock.patch.object(eng.fetch, "UA", NEUTRAL_UA))
        if d.get("hide_publication"):
            st.enter_context(hidden_publication(eng, d["hide_publication"]))
        o = observe(eng, q, eng.check(q))
    corpus.live += [x.model_dump() for x in eng.INDEX.docs[n0:]]  # what the live provider delivered (quote check)
    checks = []
    if d.get("hide_publication"):
        local = any(HIDDEN in e.url or HIDDEN in e.doc_id for c in o.res.claims for e in c.evidence)
        checks.append(Check("harness: the local copy of the publication did not reach the answer", not local, "the hidden local copy is among the evidence"))
    raw = dump(o, "live Google Fact Check" + (", local copy hidden" if d.get("hide_publication") else ""))
    raw["live_documents_added"] = [{"id": x.id, "url": x.url, "tags": x.tags} for x in eng.INDEX.docs[n0:]]
    return checks + both(sc, o, eng, corpus), got_line(o), [raw], None


def drive_image(sc, eng, pages, corpus):
    img = ROOT / sc["drive"]["image"]
    fields = [f for f in IMAGE_FIELDS if f in eng.CheckRequest.model_fields]
    probe = eng.meta._wa_process({"entry": [{"changes": [{"value": {"messages": [
        {"from": "48500100300", "type": "image", "image": {"id": "organizers-test"}}]}}]}]}, demo=True)
    second = norm(probe[0]["body"]) if probe else ""
    if not img.is_file():
        return [Check("screenshot fixture exists", False, f"{img} missing — run make_fixtures.py")], "no fixture", [], None
    if not fields:
        why = (f"image input is not implemented: CheckRequest accepts only {sorted(eng.CheckRequest.model_fields)} "
               f"(none of {list(IMAGE_FIELDS)}), there is no OCR module; the chat adapter answers an image with: “{second[:150]}…”")
        return [Check("the system accepts an image", False, why)], "unsupported input: image", [{"label": "second channel, image message", "reply": second}], why
    field = fields[0]
    value = str(img) if field == "image_path" else base64.b64encode(img.read_bytes()).decode()
    q = sc["question"]
    o = observe(eng, q, eng.run_check(eng.CheckRequest(**{"text": q, field: value})))
