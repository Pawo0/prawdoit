def regressions(baseline: dict, results: list[dict]) -> list[str]:
    now = {r["id"]: r for r in results}
    out = []
    for b in baseline.get("scenarios", []):
        r = now.get(b["id"])
        if r is None:
            continue  # not part of this run (--only / --tier)
        if b["outcome"] == "PASS" and r["outcome"] != "PASS":
            out.append(f"{b['id']}: passed in the baseline, now {r['outcome']} — {r['reason'][:200]}")
        cur = {c["name"]: c["ok"] for c in r["checks"]}
        for c in b["checks"]:
            if c["gating"] and c["ok"] and cur.get(c["name"]) is False:
                out.append(f"{b['id']}: check “{c['name']}” passed in the baseline and fails now")
    return list(dict.fromkeys(out))


