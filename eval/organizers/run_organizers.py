def read_key_file(path: str) -> None:
    """Take ONLY the Google Fact Check key from a dotenv-style file (the application does not load .env itself)."""
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        name, _, value = line.strip().removeprefix("export ").partition("=")
        if name.strip() == KEY_VAR and value.strip():
            os.environ[KEY_VAR] = value.strip().strip("'\"")


def scrub(obj):
    """Remove secrets from anything that is printed or written."""
    if not SECRETS:
        return obj
    text = json.dumps(obj, ensure_ascii=False)
    for sec in SECRETS:
        text = text.replace(json.dumps(sec, ensure_ascii=False)[1:-1], "***")
    return json.loads(text)


def bootstrap() -> Path:
    """Reproducible environment. Must run before `prawdowid` is imported (its config is read at import time)."""
    runtime = Path(tempfile.mkdtemp(prefix="prawdowid-organizers-"))
    os.environ["PRAWDOWID_RUNTIME_DIR"] = str(runtime)  # own empty database: case counters start from zero
    # the embedding cache is rewritten whenever the corpus has texts it has not seen: work on a copy, so the run
    # leaves the (tracked) files in data/index alone
    index_src = Path(os.environ.get("PRAWDOWID_INDEX_DIR", str(ROOT / "data" / "index")))
    if index_src.is_dir():
        shutil.copytree(index_src, runtime / "index")
    os.environ["PRAWDOWID_INDEX_DIR"] = str(runtime / "index")
    os.environ["PRAWDOWID_LIVE_SEARCH"] = "0"
    os.environ["PRAWDOWID_SCHEDULER"] = "0"
    key = os.environ.pop(KEY_VAR, "").strip()  # kept aside: only the network tier puts it back, per scenario
    if key:
        SECRETS.append(key)
    for k in ("FORCE_FAIL", "BRAVE_KEY", "SEARXNG_URL", "LLM_BASE_URL", "LLM_API_KEY", "LLM_MODEL"):
        os.environ.pop(f"PRAWDOWID_{k}", None)
    if _models_cached():
        os.environ.setdefault("HF_HUB_OFFLINE", "1")  # models are local: do not ask the hub for updates
    sys.path.insert(0, str(ROOT / "backend"))
    return runtime


