def load_scenarios() -> list[dict]:
    path = HERE / "scenarios.jsonl"
    scs = [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]
    rows, problems = docx_rows(), []
    for sc in scs:
        row = rows[sc["docx_row"]]
        for key, cell in (("organizers_label", row[0]), ("question_template", row[1]), ("example_answer", row[2])):
            if sc[key] != cell:
                problems.append(f"{sc['id']}: {key} differs from row {sc['docx_row']} of the document")
    covered = {sc["docx_row"] for sc in scs if not sc.get("derived")}
    problems += [f"row {i} of the document ({rows[i][0]}) has no scenario" for i in range(1, len(rows)) if i not in covered]
    if problems:
        print("scenarios.jsonl is out of sync with", DOCX.name, "— run build_scenarios.py:\n  " + "\n  ".join(problems), file=sys.stderr)
        sys.exit(2)
    return scs


def git_info() -> dict:
    def run(*a):
        try:
            return subprocess.run(["git", "-C", str(ROOT), *a], capture_output=True, text=True, timeout=10).stdout.strip()
        except Exception:  # noqa: BLE001
            return ""
    return {"commit": run("rev-parse", "--short", "HEAD"), "branch": run("rev-parse", "--abbrev-ref", "HEAD"),
            "backend_dirty": bool(run("status", "--porcelain", "--untracked-files=no", "--", "backend/prawdowid", "data/corpus", "data/sources"))}


def cell(s: str, n: int) -> str:
    s = norm(s)
    return (s if len(s) <= n else s[: n - 1] + "…").ljust(n)


def print_table(results: list[dict], allow_gaps: bool) -> None:
    print("\n" + " | ".join([cell("scenario", 30), cell("expected", 62), cell("got", 62), "result", "reason"]))
    print("-" * 230)
    for r in results:
        mark = "GAP " if (r["outcome"] == "UNSUPPORTED" and allow_gaps) else {"PASS": "PASS", "FAIL": "FAIL", "UNSUPPORTED": "FAIL"}[r["outcome"]]
        print(" | ".join([cell(r["id"], 30), cell(r["expected"], 62), cell(r["got"], 62), mark.ljust(6), norm(r["reason"])[:260]]))


def letters(results: list[dict]) -> dict[str, str]:
    out: dict[str, str] = {}
    for r in results:
        prev = out.get(r["scenario"], "PASS")
        out[r["scenario"]] = "FAIL" if "FAIL" in (prev, r["outcome"]) else ("UNSUPPORTED" if "UNSUPPORTED" in (prev, r["outcome"]) else "PASS")
    return out


